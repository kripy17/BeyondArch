import { afterEach, describe, expect, it, vi } from "vitest";
import {
  buildReportMarkdown,
  isReportType,
  provenanceClaimRows,
  REPORT_TYPES,
  reportSectionsFor,
  technicalSummary,
} from "@/lib/report";
import type { Edge } from "@/lib/provenance";
import { LS_PROVENANCE } from "@/lib/provenance";
import type { Case } from "@/data/case";

const PINNED = "2026-08-25T10:00:00.000Z";

function stubStorage(initial: Record<string, string> = {}) {
  const map = new Map(Object.entries(initial));
  vi.stubGlobal("localStorage", {
    getItem: (k: string) => (map.has(k) ? map.get(k)! : null),
    setItem: (k: string, v: string) => void map.set(k, v),
    removeItem: (k: string) => void map.delete(k),
    clear: () => void map.clear(),
  });
}

afterEach(() => {
  vi.unstubAllGlobals();
});

const mkCase = (): Case => ({
  id: "c1",
  title: "Phishing Wave",
  tags: [],
  state: "active",
  createdAt: "2026-08-01T00:00:00.000Z",
  entries: [],
  events: [
    {
      id: "evt1",
      ts: "2026-08-02T03:04:05.000Z",
      kind: "case_note_added",
      category: "case",
      importance: "low",
      actor: "analyst",
      origin: "test",
      title: "Analyst note",
      detail: "checked the lure",
      references: [],
    },
  ],
  artifacts: [{ id: "a1", kind: "email", title: "lure", metadata: {}, created: "2026-08-01T00:00:00.000Z" }],
  findings: [{ id: "f1", severity: "high", title: "Suspicious login", detail: "", source: "siem", technique: "T1078" }],
  iocs: [{ id: "i1", value: "1.2.3.4", type: "ipv4", context: "", source: "siem", severity: "medium" }],
  evidenceItems: [],
});

const edge = (relation: Edge["relation"], from: Edge["from"], to: Edge["to"]): Edge => ({
  id: `e-${relation}-${from.kind}:${from.id}-${to.kind}:${to.id}`,
  relation,
  from,
  to,
  source: "test",
  ts: "2026-08-02T00:00:00.000Z",
});

describe("deterministic templates", () => {
  it("is byte-stable for identical inputs when generation time is pinned", () => {
    const a = buildReportMarkdown(mkCase(), "technical", [], { generatedAt: PINNED });
    const b = buildReportMarkdown(mkCase(), "technical", [], { generatedAt: PINNED });
    expect(a).toBe(b);
  });

  it("only the footer stamp changes when generation time differs", () => {
    const a = buildReportMarkdown(mkCase(), "technical", [], { generatedAt: PINNED });
    const b = buildReportMarkdown(mkCase(), "technical", [], { generatedAt: "2027-01-01T00:00:00.000Z" });
    expect(a).not.toBe(b);
    expect(a.replace(PINNED, "")).toBe(b.replace("2027-01-01T00:00:00.000Z", ""));
  });

  it("renders stored timestamps as ISO strings, never locale-formatted", () => {
    const md = buildReportMarkdown(mkCase(), "incident-response", [], { generatedAt: PINNED });
    expect(md).toContain("`2026-08-02T03:04:05.000Z` **Analyst note**");
    expect(md).toContain("created 2026-08-01T00:00:00.000Z");
    expect(md).toMatch(/Generated by BeyondLabs Case Report · 2026-08-25T10:00:00\.000Z_/);
    expect(md).not.toMatch(/\d{1,2}\/\d{1,2}\/\d{4}/);
  });

  it("states created-at instead of wall-clock age in the technical summary", () => {
    const lines = technicalSummary(mkCase());
    expect(lines[0]).toContain("created 2026-08-01T00:00:00.000Z");
    expect(lines.join("\n")).not.toContain("day(s) old");
  });
});

describe("ioc-annex template", () => {
  it("is registered and selectable", () => {
    expect(isReportType("ioc-annex")).toBe(true);
    expect(REPORT_TYPES.find((t) => t.id === "ioc-annex")?.label).toBe("IOC Annex");
    expect(reportSectionsFor("ioc-annex")).toEqual(["summary", "ioc"]);
  });

  it("emits counts plus the indicator list only", () => {
    const md = buildReportMarkdown(mkCase(), "ioc-annex", [], { generatedAt: PINNED });
    expect(md).toContain("## Executive Summary");
    expect(md).toContain("## IOC Summary");
    expect(md).toContain("`1.2.3.4`");
    expect(md).not.toContain("## Timeline");
    expect(md).not.toContain("## Findings");
    expect(md).not.toContain("Claim → evidence appendix");
  });
});

describe("provenance appendix", () => {
  it("reports claims as unlinked when no graph edges exist — never fabricates ids", () => {
    stubStorage();
    const rows = provenanceClaimRows(mkCase());
    expect(rows.map((r) => r.linked)).toEqual([false, false]);
    const md = buildReportMarkdown(mkCase(), "technical", [], { generatedAt: PINNED });
    expect(md).toContain("not yet linked to recorded evidence");
    expect(md).toContain("### Claim → evidence appendix");
  });

  it("links each claim back to its supporting nodes via the graph spine", () => {
    const edges: Edge[] = [
      edge("produced", { kind: "artifact", id: "a1" }, { kind: "evidence", id: "ev1" }),
      edge("supports", { kind: "evidence", id: "ev1" }, { kind: "finding", id: "f1" }),
      edge("extracts", { kind: "finding", id: "f1" }, { kind: "ioc", id: "i1" }),
    ];
    stubStorage({ [LS_PROVENANCE]: JSON.stringify(Object.fromEntries(edges.map((e) => [e.id, e]))) });

    const rows = provenanceClaimRows(mkCase());
    const findingRow = rows.find((r) => r.claimKind === "finding")!;
    expect(findingRow.linked).toBe(true);
    expect(findingRow.chain).toEqual(["artifact:a1", "evidence:ev1", "finding:f1"]);

    const iocRow = rows.find((r) => r.claimKind === "ioc")!;
    expect(iocRow.linked).toBe(true);
    expect(iocRow.chain).toEqual(["artifact:a1", "evidence:ev1", "finding:f1", "ioc:i1"]);

    const md = buildReportMarkdown(mkCase(), "incident-response", [], { generatedAt: PINNED });
    expect(md).toContain("[finding] **Suspicious login** (`f1`) ← evidence:ev1 ← artifact:a1");
    expect(md).toContain("[ioc] **1.2.3.4** (`i1`) ← finding:f1 ← evidence:ev1 ← artifact:a1");
  });

  it("marks legacy IOCs without stable ids as unlinked", () => {
    stubStorage();
    const c = mkCase();
    c.iocs = [{ value: "evil.test", type: "domain", context: "", source: "manual", severity: "medium" }];
    const rows = provenanceClaimRows(c);
    const domain = rows.find((r) => r.label === "evil.test")!;
    expect(domain.claimId).toBe("");
    expect(domain.linked).toBe(false);
  });
});
