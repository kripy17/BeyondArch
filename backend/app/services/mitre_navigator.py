from typing import Any
from app.utils import utc_now

NAVIGATOR_VERSION = "4.5"
ATTACK_VERSION = "15"
DOMAIN = "enterprise-attack"


def generate_navigator_layer(
    name: str = "BeyondLabs SOC Detection Coverage",
    description: str = "Defensive coverage layer generated by BeyondLabs Detection Engineering Lab",
    techniques: list[dict[str, Any]] | None = None,
    platforms: list[str] | None = None,
    domain: str = DOMAIN,
) -> dict[str, Any]:
    """
    Builds a valid MITRE ATT&CK Navigator Layer v4.5 standard JSON document.
    """
    if platforms is None:
        platforms = ["Windows", "Linux", "macOS", "IaaS", "SaaS", "Office 365", "Identity"]

    formatted_techniques = []
    if techniques:
        for t in techniques:
            tech_id = t.get("techniqueID") or t.get("id", "")
            if not tech_id:
                continue

            score = t.get("score", 100 if t.get("coverage") == "full" else 50 if t.get("coverage") == "partial" else 0)
            color = t.get("color")
            if not color:
                if score >= 80:
                    color = "#22c55e"  # green
                elif score >= 30:
                    color = "#eab308"  # yellow/amber
                else:
                    color = "#334155"  # slate

            tech_entry: dict[str, Any] = {
                "techniqueID": tech_id.upper(),
                "tactic": (t.get("tactic") or "execution").lower().replace(" ", "-"),
                "score": score,
                "color": color,
                "comment": t.get("comment") or t.get("note") or f"Coverage: {score}%",
                "enabled": t.get("enabled", True),
            }

            metadata = t.get("metadata")
            if metadata:
                tech_entry["metadata"] = metadata

            formatted_techniques.append(tech_entry)

    layer = {
        "name": name,
        "versions": {
            "attack": ATTACK_VERSION,
            "navigator": NAVIGATOR_VERSION,
            "layer": NAVIGATOR_VERSION,
        },
        "domain": domain,
        "description": f"{description} · Generated at {utc_now()}",
        "filters": {
            "platforms": platforms,
        },
        "sorting": 0,
        "layout": {
            "layout": "side",
            "aggregateFunction": "average",
            "showID": True,
            "showName": True,
            "showTechniqueCount": True,
        },
        "hideDisabled": False,
        "gradient": {
            "colors": ["#1e293b", "#eab308", "#22c55e"],
            "minValue": 0,
            "maxValue": 100,
        },
        "legendItems": [
            {"label": "Full Deployed Detection (score: 100)", "color": "#22c55e"},
            {"label": "Partial / In Development (score: 50)", "color": "#eab308"},
            {"label": "Uncovered / Gap (score: 0)", "color": "#1e293b"},
        ],
        "techniques": formatted_techniques,
    }

    return layer


def parse_navigator_layer(layer_data: dict[str, Any]) -> dict[str, Any]:
    """
    Parses an uploaded MITRE ATT&CK Navigator layer JSON and extracts techniques,
    scores, coverage mapping, and metadata.
    """
    if not isinstance(layer_data, dict):
        raise ValueError("Invalid Navigator layer: root must be a JSON object")

    name = layer_data.get("name", "Imported Layer")
    domain = layer_data.get("domain", DOMAIN)
    versions = layer_data.get("versions", {})
    techniques = layer_data.get("techniques", [])

    parsed_techniques = []
    coverage_map = {}
    stats = {"full": 0, "partial": 0, "none": 0, "total": 0}

    for t in techniques:
        if not isinstance(t, dict):
            continue
        tid = (t.get("techniqueID") or "").upper().strip()
        if not tid:
            continue

        score = t.get("score", 0)
        color = t.get("color")
        comment = t.get("comment", "")
        tactic = t.get("tactic", "")

        cov = "none"
        if score >= 80:
            cov = "full"
            stats["full"] += 1
        elif score >= 20:
            cov = "partial"
            stats["partial"] += 1
        else:
            stats["none"] += 1

        stats["total"] += 1
        coverage_map[tid] = cov

        parsed_techniques.append({
            "techniqueID": tid,
            "tactic": tactic,
            "score": score,
            "color": color,
            "comment": comment,
            "coverage": cov,
        })

    return {
        "valid": True,
        "name": name,
        "domain": domain,
        "versions": versions,
        "total_techniques": len(parsed_techniques),
        "stats": stats,
        "coverage_map": coverage_map,
        "techniques": parsed_techniques,
    }
